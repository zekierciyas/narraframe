package com.narraframe.services

import com.narraframe.platform.generateLocalLLMText
import com.narraframe.util.AppLogger

/**
 * Text generation via llama.cpp CLI binary + a local GGUF model.
 * Requires the llama-cli binary and a GGUF model file to be downloaded first.
 *
 * Works fully offline — no network connection needed after the initial download.
 *
 * @param modelPath   Absolute path to the GGUF model file
 * @param llamaBinPath Absolute path to the llama-cli binary
 * @param modelName   Display name of the model (for logging)
 */
class LocalOfflineLLMProvider(
    private val modelPath:    String,
    private val llamaBinPath: String,
    private val modelName:    String = modelPath.substringAfterLast('/')
) : AIProvider {

    override suspend fun generateText(prompt: String): String {
        AppLogger.info("🤖 Local LLM ($modelName) — generating text…")
        val formatted = buildPrompt(
            system = "You are a professional creative writer and storyteller. Be concise.",
            user   = prompt
        )
        return generateLocalLLMText(formatted, modelPath, llamaBinPath, maxTokens = 900)
    }

    override suspend fun generateNarrationScript(userPrompt: String): String {
        AppLogger.info("🤖 Local LLM ($modelName) — generating narration script…")
        val formatted = buildPrompt(
            system = "You are a professional scriptwriter for narrated audio content. " +
                     "Write scripts that feel warm, conversational, and natural for text-to-speech synthesis.",
            user   = """
                Create an engaging narration script for: "$userPrompt"

                Requirements:
                - Conversational tone, short sentences (≤ 20 words)
                - Natural commas and periods for pacing
                - 400–600 words total
                - No stage directions or markdown – spoken narration only
                - Captivating opening; memorable close
            """.trimIndent()
        )
        return generateLocalLLMText(formatted, modelPath, llamaBinPath, maxTokens = 900)
    }

    /**
     * Same instructions as the default, but the output is constrained to a JSON array of
     * exactly [count] strings, so small models cannot return objects or prose.
     */
    override suspend fun generateImagePrompts(scenes: List<String>, baseImageStyle: String): List<String> {
        val count = scenes.size
        AppLogger.info("🤖 Local LLM ($modelName) — writing $count image prompts…")
        // maxLength stops a small model from looping inside one string until the token limit
        val schema = """{"type":"array","items":{"type":"string","minLength":20,"maxLength":320},"minItems":$count,"maxItems":$count}"""
        val formatted = buildPrompt(
            system = "You are a creative director who writes prompts for an image generator.",
            user   = imagePromptInstructions(scenes, baseImageStyle)
        )
        var best = emptyList<String>()
        repeat(2) { attempt ->
            // ~70 tokens per prompt plus JSON overhead
            val raw = generateLocalLLMText(formatted, modelPath, llamaBinPath, maxTokens = 120 + count * 90, jsonSchema = schema)
            val prompts = parseJsonStringArray(raw, count).filter(::isUsablePrompt)
            if (prompts.size == count) return prompts
            if (prompts.size > best.size) best = prompts
            AppLogger.warning("Text model returned ${prompts.size}/$count usable prompts (attempt ${attempt + 1}); " +
                if (attempt == 0) "retrying" else "using what it gave")
        }
        if (best.isEmpty()) throw Exception("The text model produced no usable image prompts. Try a larger text model in Settings → Models.")
        return best
    }

    /** Rejects empty, runaway or looping output such as "lightning lightning lightning …". */
    private fun isUsablePrompt(p: String): Boolean {
        val words = p.lowercase().split(Regex("\\W+")).filter { it.isNotEmpty() }
        if (words.size < 5 || p.length > 400) return false
        return words.toSet().size >= words.size * 0.5
    }

    override suspend fun generateImage(prompt: String): ByteArray =
        throw UnsupportedOperationException(
            "Local LLM does not support image generation. " +
            "Images are generated by the local Stable Diffusion engine."
        )

    // ── Prompt formatting ─────────────────────────────────────────────────────

    /**
     * Format system + user message in a way most GGUF instruction-tuned models understand.
     * Uses Llama 3 chat template tokens (Llama 3.x models), which degrades gracefully on
     * other models (Phi, Mistral, etc.) since they just see the text content.
     */
    private fun buildPrompt(system: String, user: String): String =
        "<|begin_of_text|>" +
        "<|start_header_id|>system<|end_header_id|>\n\n$system<|eot_id|>" +
        "<|start_header_id|>user<|end_header_id|>\n\n$user<|eot_id|>" +
        "<|start_header_id|>assistant<|end_header_id|>\n\n"
}

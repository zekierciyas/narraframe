package com.narraframe.services

import com.narraframe.util.AppLogger
import io.ktor.client.*
import io.ktor.client.call.*
import io.ktor.client.request.*
import io.ktor.http.*
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Text generation via any OpenAI-compatible local server (Ollama, LM Studio, etc.).
 *
 * Sends requests to  POST <baseUrl>/v1/chat/completions  with a JSON body identical
 * to the OpenAI Chat Completions API.  No API key is required.
 *
 * Typical base URLs:
 *   Ollama    → http://localhost:11434
 *   LM Studio → http://localhost:1234
 */
class LocalLLMProvider(
    private val baseUrl: String,
    private val model:   String
) : AIProvider {

    private val client: HttpClient = buildHttpClient()

    override suspend fun generateText(prompt: String): String {
        AppLogger.info("🤖 Local LLM ($model) — generating text…")
        return chat(
            systemMsg = "You are a professional creative writer and storyteller. Be concise.",
            userMsg   = prompt
        )
    }

    override suspend fun generateNarrationScript(userPrompt: String): String {
        AppLogger.info("🤖 Local LLM ($model) — generating narration script…")
        return chat(
            systemMsg = """
                You are a professional scriptwriter for narrated audio content.
                Write scripts that feel warm, conversational, and natural for text-to-speech synthesis.
            """.trimIndent(),
            userMsg   = """
                Create an engaging narration script for: "$userPrompt"

                Requirements:
                - Conversational tone, short sentences (≤ 20 words)
                - Natural commas and periods for pacing
                - 400–600 words total
                - No stage directions or markdown – spoken narration only
                - Captivating opening; memorable close
            """.trimIndent()
        )
    }

    override suspend fun generateImage(prompt: String): ByteArray =
        throw UnsupportedOperationException(
            "Local LLM does not support image generation. " +
            "Images are generated by the local Stable Diffusion engine."
        )

    // ── Private ───────────────────────────────────────────────────────────────

    private suspend fun chat(systemMsg: String, userMsg: String): String {
        val url = baseUrl.trimEnd('/')
        try {
            val response = client.post("$url/v1/chat/completions") {
                contentType(ContentType.Application.Json)
                setBody(ChatRequest(
                    model    = model,
                    messages = listOf(
                        ChatMsg(role = "system", content = systemMsg),
                        ChatMsg(role = "user",   content = userMsg)
                    )
                ))
            }
            return when (response.status.value) {
                in 200..299 -> {
                    val chatResp = response.body<ChatResponse>()
                    val content  = chatResp.choices.firstOrNull()?.message?.content
                        ?: throw Exception("Empty response from local LLM")
                    AppLogger.success("✓ Local LLM response (${content.length} chars)")
                    content
                }
                else -> {
                    val body = response.body<String>().take(200)
                    throw Exception("Local LLM error ${response.status.value}: $body")
                }
            }
        } catch (e: ApiError) {
            AppLogger.error("Local LLM request failed: ${e.message}")
            throw e
        } catch (e: Exception) {
            AppLogger.error("Local LLM request failed: ${e.message}")
            throw e
        }
    }

    // ── Request / response models ─────────────────────────────────────────────

    @Serializable private data class ChatMsg(val role: String, val content: String)

    @Serializable private data class ChatRequest(
        val model:    String,
        val messages: List<ChatMsg>,
        @SerialName("stream") val stream: Boolean = false
    )

    @Serializable private data class ChatResponse(val choices: List<Choice>) {
        @Serializable data class Choice(val message: ChatMsg)
    }
}
